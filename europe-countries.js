export function combineEuropeBoundaries(localFeatures = [], worldFeatures = []) {
  const countryCodes = new Set(EUROPE_COUNTRIES.map(({ code }) => code));
  const featuresByCountry = new Map();
  for (const feature of localFeatures) {
    const code = feature?.properties?.countryCode;
    if (countryCodes.has(code) && ["Polygon", "MultiPolygon"].includes(feature.geometry?.type)) {
      featuresByCountry.set(code, feature);
    }
  }
  for (const feature of worldFeatures) {
    const iso3 = feature?.id || feature?.properties?.ISO_A3 || feature?.properties?.iso_a3;
    const code = EUROPE_ISO3_CODES.get(iso3);
    if (code && ["Polygon", "MultiPolygon"].includes(feature.geometry?.type)) {
      featuresByCountry.set(code, { ...feature, properties: { ...feature.properties, countryCode: code } });
    }
  }
  return [...featuresByCountry.values()];
}

